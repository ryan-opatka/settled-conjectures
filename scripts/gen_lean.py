# Generates the Lean data and chunk files for the proof that Sun's Conjecture 4.6 fails at
# n = 267497:  Sun46/Data.lean  (the 1752 values of m)  and  Sun46/Chunks/*.lean
# (the kernel sweep over k, cut into pieces that fit in memory).
# Run from the repository root:  python3 scripts/gen_lean.py
import json, os, textwrap
N = 267497
CHUNK = 2000          # values of k per theorem (about 1.1 GB of kernel memory each)
FILES = 8             # chunk files, built in parallel by lake
root = os.path.join(os.path.dirname(__file__), '..')
d = json.load(open(os.path.join(os.path.dirname(__file__), 'certificate_267497.json')))
ms = [r[0] for r in d['admissible_m']]
assert ms == sorted(ms) and len(ms) == 1752
body = '\n   '.join(textwrap.wrap(', '.join(map(str, ms)), 92))
open(os.path.join(root, 'Sun46/Data.lean'), 'w').write(f'''import Sun46.Arith

/-! Generated by `scripts/gen_lean.py`. The 1752 values of `m` that occur for
`n = 267497` with `m - 1` and `m + 1` both prime. -/

namespace Sun46

/-- The values `m = φ(k) + φ(267497 - k)/4` with `m - 1` and `m + 1` prime. -/
def mList : List ℕ :=
  [{body}]

end Sun46
''')
chunks = []
a = 1
while a < N:
    c = min(CHUNK, N - a)
    chunks.append((a, c)); a += c
per = -(-len(chunks) // FILES)
os.makedirs(os.path.join(root, 'Sun46/Chunks'), exist_ok=True)
names = []
for f in range(FILES):
    part = list(enumerate(chunks))[f * per:(f + 1) * per]
    if not part: continue
    lines = ['import Sun46.Sweep', '',
             '/-! Generated by `scripts/gen_lean.py`. Each theorem checks a run of values of `k`',
             'inside the kernel. -/', '', 'namespace Sun46', '']
    for i, (a, c) in part:
        lines.append(f'theorem chunk_{i} : rangeOK {N} Sbits {a} {c} = true := by decide +kernel')
    lines += ['', 'end Sun46', '']
    open(os.path.join(root, f'Sun46/Chunks/C{f}.lean'), 'w').write('\n'.join(lines))
    names.append(f'Sun46.Chunks.C{f}')
lines = [f'import {m}' for m in names] + ['',
    '/-! Generated by `scripts/gen_lean.py`. The chunks, joined. -/', '', 'namespace Sun46', '']
tot = chunks[0][1]
lines.append(f'theorem glue_0 : rangeOK {N} Sbits 1 {tot} = true := chunk_0')
for i, (a, c) in list(enumerate(chunks))[1:]:
    lines.append(f'theorem glue_{i} : rangeOK {N} Sbits 1 {tot + c} = true :=')
    lines.append(f'  rangeOK_glue (by norm_num) (by norm_num) glue_{i-1} chunk_{i}')
    tot += c
assert tot == N - 1
lines += ['', f'/-- Every `k` from `1` to `{N - 1}` passes the check. -/',
          f'theorem sweep_all : rangeOK {N} Sbits 1 {N - 1} = true := glue_{len(chunks)-1}', '', 'end Sun46', '']
open(os.path.join(root, 'Sun46/Chunks/All.lean'), 'w').write('\n'.join(lines))
print(len(chunks), 'chunks in', len(names), 'files')
