# Generates Sun46/Table.lean: for each of the 1752 values of m, the triple
# (m, q(m), f) where f is a prime factor of q(m) + 1, or 0 when the certificate is Fermat's
# test to base 2. q(m) is computed here by Euler's pentagonal recurrence; Lean does not trust
# these values, it re-derives them (`q_table` in Sun46/Values.lean).
# Run from the repository root:  python3 scripts/gen_table.py
import json, os
from gmpy2 import mpz, powmod
here = os.path.dirname(__file__)
root = os.path.join(here, '..')
d = json.load(open(os.path.join(here, 'certificate_267497.json')))
rows = d['admissible_m']
N = max(r[0] for r in rows)
pent = []
k = 1
while k * (3 * k - 1) // 2 <= N:
    pent.append((k * (3 * k - 1) // 2, k % 2 == 1))
    if k * (3 * k + 1) // 2 <= N: pent.append((k * (3 * k + 1) // 2, k % 2 == 1))
    k += 1
p = [mpz(0)] * (N + 1); p[0] = mpz(1)
for n in range(1, N + 1):
    s = mpz(0)
    for g, odd in pent:
        if g > n: break
        if odd: s += p[n - g]
        else: s -= p[n - g]
    p[n] = s
def q(n):
    s = p[n]; j = 1
    while True:
        a = j * (3 * j - 1); b = j * (3 * j + 1)
        if a > n: break
        s += -p[n - a] if j % 2 else p[n - a]
        if b <= n: s += -p[n - b] if j % 2 else p[n - b]
        j += 1
    return s
assert [int(q(i)) for i in range(1, 13)] == [1, 1, 2, 2, 3, 4, 5, 6, 8, 10, 12, 15]
trip = []
for m, kmin, cnt, cert in rows:
    v = q(m)
    if cert == 'fermat2':
        assert v >= 2 and powmod(2, v, v + 1) != 1
        f = 0
    else:
        f = int(cert)
        assert 2 <= f < v + 1 and (v + 1) % f == 0
    assert v < 2 ** 1504
    trip.append((m, int(v), f))
PARTS = 12
per = -(-len(trip) // PARTS)
out = ['import Sun46.Arith', '', 'set_option linter.style.longLine false', '',
       '/-! Generated by `scripts/gen_table.py`. Triples `(m, v, f)`: `v` is the claimed value',
       'of `q m`, and `f` is a prime factor of `v + 1`, or `0` when `v + 1` fails Fermat\'s test to',
       'base `2`. Nothing here is trusted: `Sun46/Values.lean` checks the values of `q`',
       'and `Sun46/Composite.lean` checks the certificates. -/', '', 'namespace Sun46', '']
names = []
for i in range(PARTS):
    part = trip[i * per:(i + 1) * per]
    if not part: continue
    names.append(f'certPart{i}')
    out.append(f'/-- Part {i} of the certificate list. -/')
    out.append(f'def certPart{i} : List (ℕ × ℕ × ℕ) :=')
    out.append('  [' + ',\n   '.join(f'({m}, {v}, {f})' for m, v, f in part) + ']')
    out.append('')
out.append('/-- All certificates. -/')
out.append('def certAll : List (ℕ × ℕ × ℕ) :=\n  ' + ' ++ '.join(names))
out += ['', 'end Sun46', '']
open(os.path.join(root, 'Sun46/Table.lean'), 'w').write('\n'.join(out))
print(len(trip), 'triples;', sum(1 for t in trip if t[2] == 0), 'Fermat;', len(names), 'parts; largest value has', len(str(max(t[1] for t in trip))), 'digits')
